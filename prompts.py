def me_instruction(me):
    """告诉纪要「哪个说话人是我」的追加指令。

    Args:
        me: 说话人代号,例如「说话人C」。空值返回空串。

    Returns:
        追加到 FINAL_SYS 后面的字符串。
    """
    if not me:
        return ""
    return (f"\n\n**重要**：转写中标记为「{me}」的说话人就是「我」本人。"
            f"在「待办事项」表格里，「{me}」名下要做的事，负责人一律写 **我**；"
            f"其他说话人写其代号或姓名，不要写「我」。")
