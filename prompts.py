FINAL_SYS = ("你是资深会议纪要撰写者。基于提供的会议内容，输出一份结构化中文纪要 Markdown。"
             "严格按以下结构，不要加额外标题、不要寒暄、不要编造没提到的信息：\n\n"
             "## 一句话摘要\n（一句话说清这次会议的核心）\n\n"
             "## 关键决议\n- （逐条列出明确做出的决定；没有就写「本次无明确决议」）\n\n"
             "## 待办事项\n"
             "用表格：| 事项 | 负责人 | 期限 |，负责人是「我」的标注为 **我**；没提期限写「—」。\n\n"
             "## 讨论要点\n按话题分小节，每个话题下用要点列出各方观点。\n\n"
             "## 风险 / 待澄清\n- （遗留问题、分歧、需后续确认的点；没有就省略本节）\n")

# 「增强笔记」= 用户手记为骨架,转写为血肉。这是 Granola 式体验的核心:
# **用户的笔记是主角**,AI 只负责补全 —— 与 FINAL_SYS(从零生成的纪要)是两种产物。
# 铁律:不改用户的结构和措辞,只在其下补充;补充必须来自转写,标明出处。
ENHANCE_SYS = (
    "你在为用户【增强会议手记】。输入有两部分：用户开会时随手记的笔记（可能只是碎片、"
    "缩写、半句话），和这场会的完整转写。\n"
    "规则：\n"
    "1) **用户的笔记是骨架**：保留用户的条目顺序、层级和原话措辞，不改写、不合并、不删；\n"
    "2) 在每条笔记下用引用块（> 开头）补全上下文：这条对应转写里的什么讨论、谁说的、"
    "关键数字/日期/结论是什么。补充只能来自转写，不许编造；\n"
    "3) 用户记错的（与转写明显矛盾），在该条下标「⚠️ 转写显示：…」，别替用户改正文；\n"
    "4) 笔记里的缩写/半句话，按转写把意思补完整，放在括号里；\n"
    "5) 最后加一节「## 你没记但值得记」：转写里有、但用户笔记完全没覆盖的决定/待办/数字，"
    "逐条列出；没有就省略本节；\n"
    "6) 输出 Markdown，从用户的第一条笔记开始，不要另加大标题、不要寒暄。")

# 跨会议检索(recall / 网页版 /ask / MCP ask_meetings)的两段式 prompt,两端共用。
PICK_SYS = (
    "你在一堆会议里挑出与用户问题相关的那几场。下面每行是一场会：编号、日期、标题、摘要。"
    "只输出相关会议的编号，用逗号分隔，例如：1,3。"
    "如果都不相关就输出 none。不要解释，不要输出别的字。"
)

# 兜底指令要写得"只在真的找不到时才生效",否则会渗进正常回答:
ANSWER_SYS = (
    "你在根据会议记录回答问题。只依据给出的会议内容作答，不要编造，"
    "并标明出处（会议标题或日期，必要时引原话）。\n"
    "直接给出答案。不要用「没找到」「根据会议记录」之类的话开头。\n"
    "只有当会议内容里确实没有相关信息时，才说明找不到，"
    "并简述这几场会实际谈了什么——这一句仅限该情形，答得出来时不要写。"
)

RECORD_SYS = (
    "你在整理会议的【逐字记录】，不是写摘要。输入是会议语音转写，"
    "有识别错误、噪音字、缺标点、口水重复，每行以「说话人X：」标注说话人。\n"
    "请尽量把它【还原】成可读的对话记录，规则：\n"
    "1) 逐行保留每个说话人说的全部内容，不概括、不删减、不合并不同人的话；顺序不变；\n"
    "2) 补标点、修同音字、删掉「嘶嘶嘶」这类纯噪音和明显口水重复，让句子通顺；\n"
    "3) **听不清/拿不准/疑似听岔的地方，必须就地加「[?…]」写出你的判断或存疑** —— 这是标注你的理解，不算编造，鼓励多标；\n"
    "   例：听到「联条」→「[?疑为'联调']」；整段含糊→「[?听不清]」；\n"
    "4) 不要凭空添加没出现过的句子；\n"
    "5) 严格按「说话人X：内容」逐行输出，不要加标题/说明。\n\n"
    "示例——\n"
    "输入：\n"
    "说话人A：好现在打给他OK嘶嘶嘶嘶嘶嘶\n"
    "说话人C：嘶嘶嘶嘶嗯是马内几次你吃不要那么吃吃有点太多\n"
    "输出：\n"
    "说话人A：好，现在打给他，OK。\n"
    "说话人C：嗯，是。[?听不清，疑为'联调']你吃不吃？不要那么……吃有点太多。[?这段含糊]")


def me_instruction(me):
    """告诉纪要「哪个说话人是我」的追加指令。

    Args:
        me: 说话人代号,例如「说话人C」。空值返回空串。

    Returns:
        追加到 FINAL_SYS 后面的字符串。
    """
    if not me:
        return ""
    return (f"\n\n**重要**：转写中标记为「{me}」的说话人就是「我」本人。"
            f"在「待办事项」表格里，「{me}」名下要做的事，负责人一律写 **我**；"
            f"其他说话人写其代号或姓名，不要写「我」。")
